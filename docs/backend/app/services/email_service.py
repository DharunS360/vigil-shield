"""
Vigil Shield — Email Service
Sends incident reports via SMTP (Gmail/Outlook).
"""
import os
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.application import MIMEApplication
from pathlib import Path
from dotenv import load_dotenv
import logging

load_dotenv()
logger = logging.getLogger(__name__)


class EmailService:
    def __init__(self):
        self.smtp_host = os.getenv("SMTP_HOST", "smtp.gmail.com")
        self.smtp_port = int(os.getenv("SMTP_PORT", "587"))
        self.smtp_user = os.getenv("SMTP_USER", "")
        self.smtp_password = os.getenv("SMTP_PASSWORD", "")
        self.from_email = os.getenv("SMTP_FROM", self.smtp_user)
        self.enabled = bool(self.smtp_user and self.smtp_password)

        if not self.enabled:
            logger.warning("Email service disabled — SMTP not configured")

    def send_report(
        self,
        to_email: str,
        subject: str,
        body: str,
        attachment_path: Path = None,
    ) -> bool:
        """Send email with optional PDF attachment."""
        if not self.enabled:
            logger.warning("Email skipped — service disabled")
            return False

        try:
            msg = MIMEMultipart()
            msg["From"] = self.from_email
            msg["To"] = to_email
            msg["Subject"] = subject
            msg.attach(MIMEText(body, "plain"))

            if attachment_path and Path(attachment_path).exists():
                with open(attachment_path, "rb") as f:
                    pdf_data = f.read()
                pdf = MIMEApplication(pdf_data, _subtype="pdf")
                pdf.add_header(
                    "Content-Disposition",
                    "attachment",
                    filename=Path(attachment_path).name,
                )
                msg.attach(pdf)

            with smtplib.SMTP(self.smtp_host, self.smtp_port, timeout=30) as server:
                server.starttls()
                server.login(self.smtp_user, self.smtp_password)
                server.send_message(msg)

            logger.info(f"Email sent: {to_email} — {subject}")
            return True

        except Exception as e:
            logger.error(f"Email failed: {e}")
            return False

    def send_incident_report(
        self,
        alert_data: dict,
        to_email: str,
        pdf_path: Path,
    ) -> bool:
        """Send incident report email."""
        subject = (
            f"[Vigil Shield] Incident Report — "
            f"{alert_data.get('type', 'Alert')} — "
            f"{alert_data.get('severity', 'LOW')}"
        )

        body = f"""Hi,

Please find attached the incident report for the following alert.

─────────────────────────────────
  ALERT SUMMARY
─────────────────────────────────
  Alert ID     : {alert_data.get('id', 'N/A')}
  Alert Type   : {alert_data.get('type', 'N/A')}
  Severity     : {alert_data.get('severity', 'N/A')}
  Source IP    : {alert_data.get('source_ip', 'N/A')}
  Target       : {alert_data.get('target', 'N/A')}
  Decision     : {alert_data.get('decision', 'N/A')}
  Status       : {alert_data.get('status', 'N/A')}
─────────────────────────────────

Full details, MITRE mapping, and IOCs are in the attached PDF report.

Generated by Vigil Shield SOC Platform
Analyst: Dharun S | SOC L1 Analyst
"""

        return self.send_report(to_email, subject, body, pdf_path)