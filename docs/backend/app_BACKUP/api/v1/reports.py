"""
Vigil Shield — Reports API
Generate, download, and email incident reports.
"""
from pathlib import Path
from fastapi import APIRouter, HTTPException, Query
from fastapi.responses import FileResponse
from pydantic import BaseModel

from app.services.report_generator import ReportGenerator
from app.services.email_service import EmailService

router = APIRouter(prefix="/api/v1/reports", tags=["reports"])

report_gen = ReportGenerator()
email_svc = EmailService()


class ReportRequest(BaseModel):
    alert_id: str
    alert_data: dict
    send_email: bool = False
    to_email: str | None = None


@router.post("/generate")
async def generate_report(req: ReportRequest):
    """Generate a PDF report for an alert."""
    try:
        pdf_path = report_gen.generate_pdf(req.alert_data)

        email_sent = False
        if req.send_email and req.to_email:
            email_sent = email_svc.send_incident_report(
                req.alert_data, req.to_email, pdf_path
            )

        return {
            "status": "success",
            "report_id": pdf_path.stem,
            "filename": pdf_path.name,
            "download_url": f"/api/v1/reports/download/{pdf_path.name}",
            "email_sent": email_sent,
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/download/{filename}")
async def download_report(filename: str):
    """Download a generated PDF report — forces browser download."""
    pdf_path = ReportGenerator.OUTPUT_DIR / filename
    if not pdf_path.exists():
        raise HTTPException(status_code=404, detail="Report not found")

    return FileResponse(
        pdf_path,
        media_type="application/pdf",
        filename=filename,
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
            "Cache-Control": "no-cache",
        },
    )


@router.get("/list")
async def list_reports():
    """List all generated reports."""
    reports = []
    for pdf in sorted(ReportGenerator.OUTPUT_DIR.glob("*.pdf"), reverse=True):
        stat = pdf.stat()
        reports.append({
            "filename": pdf.name,
            "report_id": pdf.stem,
            "size_bytes": stat.st_size,
            "created_at": stat.st_mtime,
            "download_url": f"/api/v1/reports/download/{pdf.name}",
        })
    return {"total": len(reports), "reports": reports}


@router.post("/email/{filename}")
async def email_report(
    filename: str,
    to_email: str = Query(..., description="Recipient email address"),
):
    """Re-send an existing report via email."""
    pdf_path = ReportGenerator.OUTPUT_DIR / filename
    if not pdf_path.exists():
        raise HTTPException(status_code=404, detail="Report not found")

    subject = f"[Vigil Shield] Incident Report — {pdf_path.stem}"
    body = (
        "Please find the requested Vigil Shield incident report attached.\n\n"
        "Generated by Vigil Shield SOC Platform\n"
        "— Dharun S | SOC L1 Analyst"
    )
    success = email_svc.send_report(to_email, subject, body, pdf_path)

    return {
        "status": "sent" if success else "failed",
        "to": to_email,
        "filename": filename,
    }